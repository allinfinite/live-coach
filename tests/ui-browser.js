async (page) => {
  const results = [];
  const assert = (value, label) => { if (!value) throw new Error(label); results.push(label); };
  await page.setViewportSize({width:460,height:900});
  await page.addInitScript(() => {
    window.calls=[];window.failStart=false;
    window.__TAURI__={core:{invoke:async(command,args)=>{
      window.calls.push({command,args});
      if(command==='environment')return {models:[{path:'/read-only/ggml-base.en.bin',label:'Whisper base.en',engine:'whisper'}],ollama:{available:true,models:['qwen2.5:3b']}};
      if(command==='load_history')return [{expires_at:1999999999,segments:[{id:'saved',text:'A retained example.',speaker:null}]}];
      if(command==='start_session'&&window.failStart)throw new Error('Microphone permission denied');
      if(command==='stop_session'||command==='delete_transcripts')window.emitCoach({type:'stopped'});
      if(command==='quick_action')window.emitCoach({type:'insight',observation:'The same request for justification has come up twice. Intent remains unclear.',suggested_response:'I hear that you disagree, and my decision is still the same.',confidence:'medium'});
      return null;
    }},event:{listen:async(name,handler)=>{window.emitCoach=data=>handler({payload:data});return ()=>{};}}};
  });
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#sttModel').value);
  await page.locator('#start').click();
  assert(await page.locator('#notice').textContent().then(s=>s.includes('Acknowledge')), 'Consent blocks recording before acknowledgement');
  assert(await page.evaluate(()=>!calls.some(c=>c.command==='start_session')), 'Blocked start does not reach backend');
  await page.locator('#settingsToggle').click();
  await page.locator('#provider').selectOption('openai');
  assert(await page.locator('#cloudSettings .warning').isVisible(), 'External provider shows transcript warning');
  assert(await page.locator('#captureNote').textContent().then(s=>s.includes('external coaching')), 'Capture note identifies external coaching');
  await page.locator('#settingsToggle').click();
  assert(await page.locator('#cloudBanner').isVisible(), 'External transcript warning remains visible with settings collapsed');
  await page.locator('#settingsToggle').click();
  await page.locator('#viewHistory').click();
  assert(await page.locator('#history').textContent().then(s=>s.includes('A retained example.')), 'Explicit history request displays retained transcripts separately');
  assert(await page.locator('.segment').count()===0, 'Retained history does not replace live transcript');
  assert(await page.evaluate(()=>!localStorage.getItem('live-coach-preferences-v1').includes('A retained example.')), 'Retained transcript never saved to localStorage');
  await page.locator('#delete').click();
  assert(await page.locator('#historyPanel').isHidden(), 'Instant deletion clears displayed retained history');
  await page.locator('#consent').check();
  await page.locator('#start').click();
  assert(await page.locator('#notice').textContent().then(s=>s.includes('external transcript')), 'Cloud transmission requires separate acknowledgement');
  await page.locator('#provider').selectOption('ollama');
  await page.locator('#simulation').check();
  await page.locator('#timerMinutes').fill('1');await page.locator('#timerMinutes').dispatchEvent('change');
  await page.locator('#start').click();
  assert(await page.locator('#start').textContent()==='Stop conversation', 'Explicit simulator start enters running state');
  assert(await page.locator('#provider').isDisabled(), 'Provider configuration locked while running');
  assert(!(await page.locator('#consent').isChecked()), 'Acknowledgement reset after start');
  await page.evaluate(()=>{emitCoach({type:'transcript',id:'one',text:'I need to leave by six.',speaker:null,timestamp_ms:1});emitCoach({type:'transcript',id:'one',text:'I need to leave by six.',speaker:null,timestamp_ms:1});emitCoach({type:'transcript',id:'two',text:'But tell me why that matters again.',speaker:'System audio',timestamp_ms:2});});
  assert(await page.locator('.segment').count()===2, 'Finalized transcript events deduplicated and displayed');
  assert(await page.locator('.speaker').count()===1, 'Labels displayed only when supplied');
  await page.locator('[data-action="suggest_reply"]').click();
  assert(await page.locator('#reply').textContent().then(s=>s.includes('decision is still')), 'Actual insight event shape renders suggested reply');
  await page.evaluate(()=>emitCoach({type:'error',message:'Ollama unavailable; try again.'}));
  assert(await page.locator('#notice').textContent().then(s=>s.includes('Ollama unavailable')), 'Inference failure is visible without stopping capture');
  await page.locator('#settingsToggle').click();
  await page.locator('#notice').evaluate(el=>el.hidden=true);
  await page.screenshot({path:'evidence/ui.png',fullPage:true});
  await page.locator('#delete').click();
  assert(await page.locator('#notice').textContent().then(s=>s.includes('Conversation stopped. Live context and retained transcripts deleted.')), 'Deletion confirms capture stopped and context purged');
  assert(!(await page.locator('#retain').isChecked()), 'Deletion disables transcript retention');
  assert(await page.locator('#start').textContent()==='Start conversation', 'Instant deletion stops the active session');
  assert(await page.locator('#start').textContent()==='Start conversation', 'Stopped event restores idle controls');
  assert(await page.locator('#timer').textContent()==='01:00', 'Timer resets after stop');
  assert(await page.locator('.segment').count()===0, 'Default non-retained transcript clears at stop');
  assert(!(await page.locator('#consent').isChecked()), 'New session requires fresh consent');
  await page.locator('#consent').check();await page.evaluate(()=>window.failStart=true);await page.locator('#start').click();
  assert(await page.locator('#notice').textContent().then(s=>s.includes('permission denied')), 'Capture startup failure displayed');
  assert(await page.locator('#provider').isEnabled() && await page.locator('#start').isEnabled(), 'Startup failure restores configuration and start controls');
  return {passed:results.length,results};
}
